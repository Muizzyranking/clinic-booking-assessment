import type {
  Booking,
  BookingPage,
  ErrorBody,
  NewBooking,
  Slot,
  SlotsResponse,
} from "./types";

// Where the API lives: VITE_API_URL (set it on Vercel). Local dev falls back to the
// backend on :8000. In a production build without it, requests fail with a clear message.
const configured = (import.meta.env.VITE_API_URL as string | undefined)
  ?.trim()
  .replace(/\/+$/, "");
const BASE = configured || (import.meta.env.DEV ? "http://localhost:8000" : "");

/** Swagger UI for the backend. */
export const DOCS_URL = `${BASE}/docs`;

export class ApiError extends Error {
  readonly status: number;
  readonly retryAfter: number | null;

  constructor(message: string, status: number, retryAfter: number | null = null) {
    super(message);
    this.name = "ApiError";
    this.status = status;
    this.retryAfter = retryAfter;
  }
}

function isErrorBody(value: unknown): value is ErrorBody {
  return (
    typeof value === "object" &&
    value !== null &&
    "error" in value &&
    typeof (value as { error: unknown }).error === "string"
  );
}

async function request<T>(path: string, key: string, init: RequestInit = {}): Promise<T> {
  const headers = new Headers(init.headers);
  headers.set("X-API-Key", key);
  if (init.body !== undefined) headers.set("Content-Type", "application/json");

  if (!BASE) {
    throw new ApiError("VITE_API_URL is not set, so the app doesn't know where the API is.", 0);
  }

  let response: Response;
  try {
    response = await fetch(`${BASE}${path}`, { ...init, headers });
  } catch {
    throw new ApiError("Can't reach the server. Check your connection and try again.", 0);
  }

  const data: unknown = await response.json().catch(() => null);
  if (!response.ok) {
    const retry = Number(response.headers.get("Retry-After"));
    throw new ApiError(
      isErrorBody(data) ? data.error : `Request failed (${response.status})`,
      response.status,
      Number.isFinite(retry) && retry > 0 ? retry : null,
    );
  }
  return data as T;
}

export interface Api {
  listSlots(): Promise<Slot[]>;
  /** Replaces everything with random demo data generated by the backend. */
  seedSlots(): Promise<Slot[]>;
  createBooking(body: NewBooking, idempotencyKey: string): Promise<Booking>;
  listBookings(email: string, cursor?: string | null): Promise<BookingPage>;
  getBooking(id: string): Promise<Booking>;
  cancelBooking(id: string): Promise<Booking>;
}

export function createApi(key: string): Api {
  return {
    async listSlots() {
      return (await request<SlotsResponse>("/slots", key)).slots;
    },
    async seedSlots() {
      return (await request<SlotsResponse>("/seed", key, { method: "POST" })).slots;
    },
    createBooking(body, idempotencyKey) {
      return request<Booking>("/bookings", key, {
        method: "POST",
        body: JSON.stringify(body),
        headers: { "Idempotency-Key": idempotencyKey },
      });
    },
    listBookings(email, cursor) {
      const params = new URLSearchParams({ email, limit: "5" });
      if (cursor) params.set("cursor", cursor);
      return request<BookingPage>(`/bookings?${params.toString()}`, key);
    },
    getBooking(id) {
      return request<Booking>(`/bookings/${encodeURIComponent(id)}`, key);
    },
    cancelBooking(id) {
      return request<Booking>(`/bookings/${encodeURIComponent(id)}`, key, {
        method: "DELETE",
      });
    },
  };
}

export function errorMessage(error: unknown): string {
  if (error instanceof ApiError) {
    if (error.status === 429 && error.retryAfter !== null) {
      return `Too many attempts for this email. Try again in ${error.retryAfter} seconds.`;
    }
    return error.message;
  }
  return "Something went wrong. Try again.";
}
